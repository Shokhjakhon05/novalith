// The design targets, measured with bots. NOVALITH_GAMES sets the number of games per bot
// (CI: 1000). With NOVALITH_REPORT=1 the numbers are also written to docs/BALANCE_REPORT.md.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:novalith/core/balance.dart';
import 'package:novalith/core/bots.dart';

final int games = int.tryParse(Platform.environment['NOVALITH_GAMES'] ?? '') ?? 100;

class Row {
  Row(this.name);
  final String name;
  final scores = <int>[];
  final drops = <int>[];
  final firstMerge = <int>[];
  final levels = <int>[];
  final chains = <int>[];
  final coins = <int>[];
  var maxBodies = 0;
  var unfinished = 0;
}

void main() {
  test('skill beats luck, runs are short, the first merge comes early ($games games per bot)', () {
    const b = Balance.standard;
    final rows = <Row>[];
    for (final entry in {'random': randomBot, 'greedy': greedyBot}.entries) {
      final row = Row(entry.key);
      for (var seed = 1; seed <= games; seed++) {
        final s = simulate(entry.value, seed);
        row.scores.add(s.score);
        row.drops.add(s.drops);
        row.firstMerge.add(s.firstMergeDrop);
        row.levels.add(s.maxLevel);
        row.chains.add(s.maxChain);
        row.coins.add(s.score ~/ b.pointsPerCoin + s.bonusCoins);
        if (s.maxBodies > row.maxBodies) row.maxBodies = s.maxBodies;
        if (!s.finished) row.unfinished++;
      }
      rows.add(row);
    }
    final random = rows[0];
    final greedy = rows[1];
    final ratio = median(greedy.scores) / median(random.scores);
    int minOf(List<int> l) => l.reduce((a, c) => a < c ? a : c);
    int maxOf(List<int> l) => l.reduce((a, c) => a > c ? a : c);

    final report = StringBuffer()
      ..writeln('# Novalith - balance report')
      ..writeln()
      ..writeln('Generated by `test/core/balance_test.dart`: $games full games per bot on seeds 1..$games, ')
      ..writeln('one drop every 0.9 s, standard balance.')
      ..writeln()
      ..writeln('| Metric | Random bot | Greedy bot |')
      ..writeln('|---|---|---|')
      ..writeln('| Median score | ${median(random.scores)} | ${median(greedy.scores)} |')
      ..writeln('| Median drops per run | ${median(random.drops)} | ${median(greedy.drops)} |')
      ..writeln('| Shortest run (drops) | ${minOf(random.drops)} | ${minOf(greedy.drops)} |')
      ..writeln('| Longest run (drops) | ${maxOf(random.drops)} | ${maxOf(greedy.drops)} |')
      ..writeln('| First merge at drop (median) | ${median(random.firstMerge)} | ${median(greedy.firstMerge)} |')
      ..writeln('| Median highest evolution | ${median(random.levels)} | ${median(greedy.levels)} |')
      ..writeln('| Best evolution seen | ${maxOf(random.levels)} | ${maxOf(greedy.levels)} |')
      ..writeln('| Median longest chain | ${median(random.chains)} | ${median(greedy.chains)} |')
      ..writeln('| Median run coins | ${median(random.coins)} | ${median(greedy.coins)} |')
      ..writeln('| Most bodies on the board | ${random.maxBodies} | ${greedy.maxBodies} |')
      ..writeln('| Games that never ended | ${random.unfinished} | ${greedy.unfinished} |')
      ..writeln()
      ..writeln('| Target | Result | Verdict |')
      ..writeln('|---|---|---|')
      ..writeln(
        '| Greedy median score >= 2.5x random | ${ratio.toStringAsFixed(2)}x | ${ratio >= 2.5 ? 'pass' : 'FAIL'} |',
      )
      ..writeln(
        '| Greedy first merge by drop 4 | ${median(greedy.firstMerge)} | ${median(greedy.firstMerge) <= 4 ? 'pass' : 'FAIL'} |',
      )
      ..writeln(
        '| Random median run 40-90 drops | ${median(random.drops)} | ${median(random.drops) >= 40 && median(random.drops) <= 90 ? 'pass' : 'FAIL'} |',
      )
      ..writeln(
        '| No run shorter than 15 drops | ${minOf(random.drops)} | ${minOf(random.drops) >= 15 ? 'pass' : 'FAIL'} |',
      )
      ..writeln(
        '| Every game ends | ${random.unfinished + greedy.unfinished} unfinished | ${random.unfinished + greedy.unfinished == 0 ? 'pass' : 'FAIL'} |',
      );
    // ignore: avoid_print
    print(report);
    if (Platform.environment['NOVALITH_REPORT'] == '1') {
      File('docs/BALANCE_REPORT.md')
        ..createSync(recursive: true)
        ..writeAsStringSync(report.toString());
    }

    expect(ratio, greaterThanOrEqualTo(2.5), reason: 'skill must matter');
    expect(median(greedy.firstMerge), lessThanOrEqualTo(4));
    expect(median(random.drops), inInclusiveRange(40, 90));
    expect(minOf(random.drops), greaterThanOrEqualTo(15));
    expect(random.unfinished + greedy.unfinished, 0);
  }, timeout: const Timeout(Duration(minutes: 60)));
}
